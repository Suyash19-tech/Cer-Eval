"""Shared enumerations. Single source of truth for statuses used by DB, API and graph."""

from enum import StrEnum


class ValidationStatus(StrEnum):
    COMPLIANT = "COMPLIANT"
    MISSING = "MISSING"
    EXPIRED = "EXPIRED"
    MISMATCH = "MISMATCH"
    NEEDS_HUMAN_REVIEW = "NEEDS_HUMAN_REVIEW"


class EligibilityStatus(StrEnum):
    PASS = "PASS"
    FAIL = "FAIL"
    PENDING_HUMAN_REVIEW = "PENDING_HUMAN_REVIEW"


class DocumentClass(StrEnum):
    X_CERTIFICATION = "X_CERTIFICATION"
    Y_CERTIFICATION = "Y_CERTIFICATION"
    Z_CERTIFICATION = "Z_CERTIFICATION"
    OTHER_CERTIFICATION = "OTHER_CERTIFICATION"
    TECHNICAL_QUOTATION = "TECHNICAL_QUOTATION"
    COMMERCIAL_QUOTATION = "COMMERCIAL_QUOTATION"
    SUPPORTING_DOCUMENT = "SUPPORTING_DOCUMENT"
    UNKNOWN = "UNKNOWN"


class WorkflowStatus(StrEnum):
    CREATED = "CREATED"
    EXTRACTING_REQUIREMENTS = "EXTRACTING_REQUIREMENTS"
    REQUIREMENTS_PENDING_CONFIRMATION = "REQUIREMENTS_PENDING_CONFIRMATION"
    REQUIREMENTS_CONFIRMED = "REQUIREMENTS_CONFIRMED"
    RUNNING = "RUNNING"
    AWAITING_HUMAN_REVIEW = "AWAITING_HUMAN_REVIEW"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
